"""
remediation.py - Generates automated remediation scripts and IaC hardening fixes.
"""

from typing import List
from models import Finding, ComplianceStatus


class RemediationGenerator:
    """Generates automated remediation playbooks across Azure CLI, AWS CLI, and PowerShell."""

    @staticmethod
    def generate_shell_script(findings: List[Finding]) -> str:
        failed_findings = [f for f in findings if f.status == ComplianceStatus.FAIL]
        lines = [
            "#!/usr/bin/env bash",
            "# ======================================================================",
            "# AUTOMATED CLOUD SECURITY REMEDIATION PLAYBOOK",
            "# Generated by Cloud Security Posture Management (CSPM) Auditor",
            "# ======================================================================",
            "set -euo pipefail",
            "",
            "echo '[*] Initiating automated cloud remediation sequence...'",
            ""
        ]

        for idx, f in enumerate(failed_findings, 1):
            lines.append(f"# [{idx}/{len(failed_findings)}] {f.rule_id}: {f.title}")
            lines.append(f"# Target: {f.resource_name} ({f.provider.value}) | Severity: {f.severity.value}")
            lines.append(f"echo '[*] Remediating {f.resource_name} ({f.rule_id})...'")
            lines.append(f"{f.remediation_cli}")
            lines.append("echo '[✓] Remediation command dispatched.'")
            lines.append("")

        lines.append("echo '[✓] Automated remediation sequence completed successfully.'")
        return "\n".join(lines)

    @staticmethod
    def generate_powershell_script(findings: List[Finding]) -> str:
        failed_findings = [f for f in findings if f.status == ComplianceStatus.FAIL]
        lines = [
            "# ======================================================================",
            "# AUTOMATED CLOUD SECURITY REMEDIATION PLAYBOOK (POWERSHELL)",
            "# Generated by Cloud Security Posture Management (CSPM) Auditor",
            "# ======================================================================",
            "$ErrorActionPreference = 'Stop'",
            "Write-Host '[*] Initiating automated cloud remediation sequence...' -ForegroundColor Cyan",
            ""
        ]

        for idx, f in enumerate(failed_findings, 1):
            lines.append(f"# [{idx}/{len(failed_findings)}] {f.rule_id}: {f.title}")
            lines.append(f"# Target: {f.resource_name} ({f.provider.value}) | Severity: {f.severity.value}")
            lines.append(f"Write-Host '[*] Remediating {f.resource_name} ({f.rule_id})...' -ForegroundColor Yellow")
            lines.append(f"{f.remediation_cli}")
            lines.append("Write-Host '[✓] Remediation command dispatched.' -ForegroundColor Green")
            lines.append("")

        lines.append("Write-Host '[✓] Automated remediation sequence completed successfully.' -ForegroundColor Green")
        return "\n".join(lines)
